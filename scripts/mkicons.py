def png(path, rows, scale):
    h = len(rows)
    w = len(rows[0])
    px = []
    for y in range(h * scale):
        row = rows[y // scale]
        line = b"\x00"
        for x in range(w * scale):
            rgba = PAL[row[x // scale]]
            line += (bytes(rgba) + b"\xff") if rgba else b"\x00\x00\x00\x00"
        px.append(line)
    raw = b"".join(px)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    out = b"\x89PNG\r\n\x1a\n"
    out += chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 6, 0, 0, 0))
    out += chunk(b"IDAT", zlib.compress(raw, 9))
    out += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(out)


def main(outroot):
    for name, grid in ICONS.items():
        assert len(grid) == 16 and all(len(r) == 16 for r in grid), name
    for size, scale in ((32, 2), (16, 1)):
        d = os.path.join(outroot, f"{size}x{size}", "apps")
        os.makedirs(d, exist_ok=True)
        for icon, grid in NAMES.items():
            png(os.path.join(d, icon + ".png"), ICONS[grid], scale)
    with open(os.path.join(outroot, "index.theme"), "w") as f:
        f.write(INDEX)


if __name__ == "__main__":
    main(sys.argv[1])
